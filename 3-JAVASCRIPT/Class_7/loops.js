// Switch Case

let day = "sunday";
switch (day) {
  case "sunday": {
    console.log("Sunday");
    break;
  }
  case "monday": {
    console.log("Monday");
    break;
  }
  case "tuesday": {
    console.log("Tuesday");
    break;
  }
  case "wednesday": {
    console.log("Wednesday");
    break;
  }
  case "thursday": {
    console.log("Thursday");
    break;
  }
  case "friday": {
    console.log("Friday");
    break;
  }
  default: {
    console.log("Saturday");
  }
}
